/* Table lookup used by questions, Table Trek and the reference screen.
   kind is 'fv' or 'pv'; returns null when the cell is not in the table, which
   is itself a teachable answer ("you'd need to use the formula"). */
window.MS.annuityFactor = function (kind, periods, rate) {
  var A = window.MS.ANNUITY;
  var ri = A.rates.indexOf(rate);
  if (ri < 0) return null;
  var rows = A[kind];
  for (var i = 0; i < rows.length; i++) if (rows[i][0] === periods) return rows[i][ri + 1];
  return null;
};
